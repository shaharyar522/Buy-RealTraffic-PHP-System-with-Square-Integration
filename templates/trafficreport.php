Did you know that 90% of all traffic companies are selling fake traffic?  They use a special PHP software that routes HTTP get requests through 
a massive list of anonymous proxy servers or IP addresses.  If you are tracking your hits, your tracking log will show that you
received a hit from a particular IP address when in fact, the hit came from one of the anonymous or fake IP addresses the script stores in a database. 

<br><br>
All the traffic sent by the fake traffic PHP script is unique and shows up as unique in the stats the company provides you.  This is why they can promise you that
your site will receive unique visitors.  You can go to any search engine and type in the keyword phrase  
"Software that sends fake hits" and you will be shocked at what they are selling to these traffic companies.

<br><br>
 We tested several traffic companies and the results were very poor.  We will not mention the scam companies we tested (because of legal concerns), 
but we are certain that they are using this type of software to produce hits.  So, before you go and waste your money, here is a list of the things to watch out for:

<ul>

<li>A company that will sells you 100,000 visitors for only $39.99. </li>
<br><br>
<li>A company that claims they can send 1,000,000 visitors to your site within 30 days or less. </li>
<br><br>
<li>A company that claims their visitors are ALL unique visitors (meaning a particular visitor will only visit your site once for the entire duration of your campaign).</li>
<br><br>
<li>A company that claims to have a long list of targeted categories for you to choose from.  There are more indicators of a scam traffic company, but I think you get the picture. </li>
</ul>


Here is one way you can test a traffic company to see if their visitors are Real:

<br><br>

1)  Never submit your actual tracking link as the url to be advertised.  Using the fake hit software, the company will just send the hits to
your tracking url and it would read in your tracking log as a real hit from a real IP address.  Instead, create a short splash page with one link on
it and that one link being your actual tracking url.  The url you should submit to the company should be the url of your splash page and NOT the
url of your tracking link.

<br><br>

For example, let's say your splash page url is http://www.catchacrook.com.  On this page, you might want to put a headline such as "Are You Looking
For A Way To Make Some Real Money?  If So, Click Here For Details!"   
<br><br>

2)  What you want to do is link your tracking url to the phrase "Click Here For Details" and submit your splash page url "http://www.catchacrook.com" to
the company.  Now here is where the actual test comes in.  If the company is sending 10,000 Real visitors to your splash page, you should get at least one click on
your tracking link "Click Here For Details".  Actually, you should get more than one hit.  But you get the point.

<br><br>
If not, you know the visitors are not real.  About a year ago, we performed this exact test. The company claimed they sent 10,000 visitors to our splash page, 
but believe it or not, we received absolutely NO clicks on our tracking link.  Isn't that crazy?  
<br><br>

NOTE:  When testing a company, make sure you purchase their cheapest traffic package.  This way if your results are not good, you would have only
wasted a few bucks.




